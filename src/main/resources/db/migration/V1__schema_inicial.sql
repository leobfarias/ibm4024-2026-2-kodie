-- ============================================================
-- V1 - Schema inicial do Sistema KODIE
--
-- Escrito para rodar sem alteracao no H2 (desenvolvimento) e no
-- PostgreSQL (producao). Os enums do Java sao gravados como texto,
-- com CHECK limitando os valores aceitos: o tipo "enum" nao e
-- portavel entre os dois bancos.
--
-- Migracoes ja aplicadas NUNCA sao editadas. Qualquer mudanca de
-- schema entra num novo arquivo V2__..., V3__..., e o Flyway aplica
-- apenas o que ainda nao rodou naquele banco.
-- ============================================================

-- Cadastro central de pessoas (secao 2.1 do documento de decisoes)
create table pessoa (
    id            bigint generated by default as identity primary key,
    nome          varchar(120) not null,
    cpf           varchar(11)  not null,
    email         varchar(120) not null,
    cargo         varchar(80)  not null,
    tipo_vinculo  varchar(20)  not null,
    situacao      varchar(20)  not null,
    data_entrada  date         not null,
    data_saida    date,

    constraint uk_pessoa_cpf unique (cpf),
    constraint ck_pessoa_tipo_vinculo check (tipo_vinculo in ('CLT', 'MEI', 'PJ', 'VOLUNTARIO')),
    constraint ck_pessoa_situacao check (situacao in ('ATIVO', 'AFASTADO', 'DESLIGADO', 'INATIVO'))
);

-- Ferias, folgas, licencas, ausencias e feriados trabalhados.
-- pessoa_id aceita nulo: ocorrencias de calendario nao pertencem a ninguem.
create table ocorrencia (
    id           bigint generated by default as identity primary key,
    tipo         varchar(25)  not null,
    data_inicio  date         not null,
    data_fim     date         not null,
    situacao     varchar(20)  not null,
    observacao   varchar(255),
    pessoa_id    bigint,

    constraint fk_ocorrencia_pessoa foreign key (pessoa_id) references pessoa (id),
    constraint ck_ocorrencia_tipo check (tipo in ('FERIAS', 'FOLGA', 'LICENCA', 'AUSENCIA', 'FERIADO_TRABALHADO')),
    constraint ck_ocorrencia_situacao check (situacao in ('PLANEJADA', 'CONFIRMADA', 'CANCELADA')),
    constraint ck_ocorrencia_periodo check (data_fim >= data_inicio)
);

-- O PostgreSQL nao indexa chaves estrangeiras sozinho, e as consultas
-- "ocorrencias da pessoa X" e "periodos da pessoa X" sao as mais frequentes.
create index ix_ocorrencia_pessoa on ocorrencia (pessoa_id);

-- Periodos aquisitivos de ferias (secao 2.3). O saldo nao e armazenado.
create table periodo_aquisitivo (
    id                bigint  generated by default as identity primary key,
    pessoa_id         bigint  not null,
    numero            integer not null,
    data_inicio       date    not null,
    data_fim          date    not null,
    dias_de_direito   integer not null,
    data_limite_gozo  date    not null,

    constraint fk_periodo_pessoa foreign key (pessoa_id) references pessoa (id),
    constraint uk_periodo_pessoa_inicio unique (pessoa_id, data_inicio)
);

create index ix_periodo_pessoa on periodo_aquisitivo (pessoa_id);

-- Usuarios do sistema. A senha e guardada apenas como hash BCrypt.
create table usuario (
    id          bigint       generated by default as identity primary key,
    login       varchar(40)  not null,
    nome        varchar(120) not null,
    senha_hash  varchar(100) not null,
    perfil      varchar(20)  not null,
    ativo       boolean      not null,
    criado_em   timestamp(6) not null,

    constraint uk_usuario_login unique (login),
    constraint ck_usuario_perfil check (perfil in ('ADMIN', 'VISUALIZADOR'))
);
